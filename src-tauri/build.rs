// Brand consts live in src/brand.rs; this script mirrors them into src/brand.ts and tauri.conf.json.
include!("src/brand.rs");

use std::error::Error;
use std::fs;

type Res<T> = Result<T, Box<dyn Error>>;

const COMMANDS: &[&str] = &[
    "search",
    "open_source",
    "copy_citation",
    "hide_window",
    "list_folders",
    "add_watched_folder",
    "remove_watched_folder",
    "get_index_status",
    "get_settings",
    "set_air_gap",
    "set_shortcut",
    "list_models",
    "export_pack",
];

/// Writes only on change: tauri-build watches tauri.conf.json, so an unconditional write loops rebuilds.
fn write_if_changed(path: &str, content: &str) -> Res<()> {
    if fs::read_to_string(path).ok().as_deref() != Some(content) {
        fs::write(path, content)?;
    }
    Ok(())
}

fn brand_ts() -> Res<String> {
    let mut out =
        String::from("// GENERATED by src-tauri/build.rs from brand.rs. Do not edit.\n\n");
    for (name, value) in [
        ("APP_NAME", APP_NAME),
        ("APP_SLUG", APP_SLUG),
        ("BUNDLE_ID", BUNDLE_ID),
        ("KEYCHAIN_SERVICE", KEYCHAIN_SERVICE),
        ("PACK_EXT", PACK_EXT),
        ("SITE_URL", SITE_URL),
    ] {
        out += &format!(
            "export const {name} = {} as const;\n",
            serde_json::to_string(value)?
        );
    }
    out += &format!(
        "export const SPONSOR_URLS = {} as const;\n",
        serde_json::to_string(SPONSOR_URLS)?
    );
    Ok(out)
}

fn tauri_conf() -> Res<String> {
    let mut conf: serde_json::Value =
        serde_json::from_str(&fs::read_to_string("tauri.conf.json")?)?;
    conf["productName"] = APP_NAME.into();
    conf["identifier"] = BUNDLE_ID.into();
    if let Some(windows) = conf["app"]["windows"].as_array_mut() {
        for w in windows {
            w["title"] = APP_NAME.into();
        }
    }
    Ok(serde_json::to_string_pretty(&conf)? + "\n")
}

fn main() -> Res<()> {
    println!("cargo:rerun-if-changed=src/brand.rs");
    write_if_changed("../src/brand.ts", &brand_ts()?)?;
    write_if_changed("tauri.conf.json", &tauri_conf()?)?;

    let manifest = tauri_build::AppManifest::new().commands(COMMANDS);
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest))?;
    Ok(())
}
