# Fails if Rust code outside the net module names a networking API, or if a networking crate reaches
# the app other than through reqwest (which only net.rs uses). Regenerates docs/network-deps.md.
set -euo pipefail
cd "$(dirname "$0")/.."

# tokio::net and the socket types cover what std::net and the HTTP crates leave out.
PATTERN='\b(reqwest|hyper|ureq|std::net|tokio::net|TcpStream|TcpListener|UdpSocket)\b'
hits=$(grep -rnIE "$PATTERN" src-tauri/src src-tauri/build.rs |
  grep -vE '^src-tauri/src/net(\.rs|/)' || true)
if [ -n "$hits" ]; then
  echo "$hits"
  echo "check-net-usage: networking API used outside src-tauri/src/net" >&2
  exit 1
fi

# Shipped dependencies of the macOS build. Dev dependencies never reach a release.
tree() { cargo tree -q --locked --color never -e normal --target aarch64-apple-darwin --manifest-path src-tauri/Cargo.toml "$@"; }
CRATES=(reqwest hyper hyper-util hyper-rustls h2 ureq curl isahc attohttpc surf hf-hub tungstenite tokio-tungstenite)
present=()
for c in "${CRATES[@]}"; do
  tree -i "$c" >/dev/null 2>&1 && present+=("$c")
done
for c in "${present[@]}"; do
  [ "$c" = reqwest ] && continue
  # A path dependency (the app itself) prints its directory; registry crates do not.
  if tree --prune reqwest -i "$c" | grep ' (/' >/dev/null; then
    tree --prune reqwest -i "$c"
    echo "check-net-usage: $c reaches the app without going through reqwest" >&2
    exit 1
  fi
done

out=docs/network-deps.md
{
  echo "<!-- GENERATED by scripts/check-net-usage.sh from cargo tree. Do not edit. -->"
  echo "# Network dependencies"
  echo
  echo "Every networking crate in the shipped macOS build (\`cargo tree -e normal --target aarch64-apple-darwin\`),"
  echo "and the path by which it reaches \`locite\`. CI fails if one reaches it without going through \`reqwest\`,"
  echo "or if Rust code outside \`src-tauri/src/net\` names \`reqwest\`, \`hyper\`, \`ureq\`, \`std::net\`, \`tokio::net\`,"
  echo "\`TcpStream\`, \`TcpListener\`, or \`UdpSocket\`. \`reqwest\` is used only by \`net::Client\`, which passes"
  echo "\`AirGapGuard::check\` before every request."
  echo
  echo "Checked for and absent: $(for c in "${CRATES[@]}"; do [[ " ${present[*]} " == *" $c "* ]] || printf '`%s` ' "$c"; done | sed 's/ $//')"
  for c in "${present[@]}"; do
    echo
    echo "## $c"
    echo
    echo '```text'
    # Versions dropped so Dependabot bumps do not change the file; a new path does.
    tree -i "$c" | sed -E 's/ v[0-9][^ ]*//; s/ \([^)]*\)//'
    echo '```'
  done
} >"$out"
echo "check-net-usage: ok (wrote $out)"
